// Generates docs/CHALLENGES.md from the question banks of all four games. Run: npm run docs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GAMES } from "../src/games/registry.js";
import { describeAnswer } from "../src/games/checkAnswer.js";

const clean = (s) => String(s).replace(/\|/g, "/").replace(/\n/g, " ");
const total = GAMES.reduce((n, g) => n + g.questions.length, 0);
let md = `# Challenge list (${total})\n\nGenerated by \`npm run docs\`. Types: choice = multiple choice, number = typed number, path = click vertices on a graph, hasse = draw edges in React Flow.\n`;

for (const g of GAMES) {
  md += `\n## ${g.icon} ${g.title} (${g.questions.length}, ${g.owner})\n\n| ID | Difficulty | Type | Topic | Question | Answer |\n|---|---|---|---|---|---|\n`;
  md += g.questions.map((q) =>
    `| ${q.id} | ${q.difficulty} | ${q.type} | ${clean(q.topic)} | ${clean(q.text)} | ${clean(describeAnswer(q))} |`).join("\n") + "\n";
}
writeFileSync(fileURLToPath(new URL("./CHALLENGES.md", import.meta.url)), md);
console.log(`docs/CHALLENGES.md written (${total} challenges)`);
